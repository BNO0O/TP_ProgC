#include <stdio.h>

struct Couleur {
    unsigned char r, g, b, a;
};

int main() {
    struct Couleur couleurs[10] = {
        {0xef, 0x78, 0x12, 0xff},
        {0x2c, 0xc8, 0x64, 0xff},
        {0x11, 0x22, 0x33, 0xff},
        {0xaa, 0xbb, 0xcc, 0xff},
        {0x12, 0x98, 0x76, 0xff},
        {0x01, 0x02, 0x03, 0xff},
        {0xde, 0xad, 0xbe, 0xff},
        {0x45, 0x67, 0x89, 0xff},
        {0x10, 0x20, 0x30, 0xff},
        {0xff, 0x00, 0x99, 0xff}
    };

    for (int i = 0; i < 10; i++) {
        printf("Couleur %d : R=%d, G=%d, B=%d, A=%d\n",
               i+1, couleurs[i].r, couleurs[i].g, couleurs[i].b, couleurs[i].a);
    }

    return 0;
}
